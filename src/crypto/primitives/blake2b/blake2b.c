#define MIN(a, b) ((a) < (b) ? (a) : (b))

struct blake2b_ctx {
    byte input_buf[BLAKE2B_BLOCK_BYTES];
    uint64_t state_h[8];
    size_t input_buf_len;
    size_t digest_len;
    uint64_t bytes_processed_t_low;
    uint64_t bytes_processed_t_high;
    bool bytes_processed_t_overflow;
};

static inline int add_to_bytes_processed(struct blake2b_ctx *ctx, size_t amnt);

/*
 * The compression function f is defined in RFC 7693, section 3.2. This
 * implementation is algorithmically generated.
 */
static void compress_fn_f(struct blake2b_ctx *ctx, const byte *input_block,
                          bool final_block);

/* Values from RFC 7693, Appendix C.2; more details in RFC 7693 section 2.6 */
static const uint64_t IV[8] = {0x6A09E667F3BCC908ULL, 0xBB67AE8584CAA73BULL,
                               0x3C6EF372FE94F82BULL, 0xA54FF53A5F1D36F1ULL,
                               0x510E527FADE682D1ULL, 0x9B05688C2B3E6C1FULL,
                               0x1F83D9ABFB41BD6BULL, 0x5BE0CD19137E2179ULL};

struct blake2b_ctx *blake2b_alloc(void)
{
    struct blake2b_ctx *ret =
        (struct blake2b_ctx *)calloc(1, sizeof(struct blake2b_ctx));
    GUARD_ALLOC(ret);
    return ret;
}

void blake2b_start(struct blake2b_ctx *ctx, size_t digest_len, const byte *key,
                   size_t key_len)
{
    ASSERT(digest_len > 0 && digest_len <= BLAKE2B_MAX_DIGEST_BYTES,
           "Invalid digest length: %zu", digest_len);
    ASSERT(key_len <= BLAKE2B_MAX_KEY_BYTES, "Invalid key length: %zu",
           key_len);

    memcpy(ctx->state_h, IV, sizeof(IV));
    ctx->state_h[0] ^= (uint64_t)0x01010000ULL | (uint64_t)(key_len << 8) |
                       (uint64_t)digest_len;

    ctx->digest_len = digest_len;
    ctx->bytes_processed_t_high = 0;
    ctx->bytes_processed_t_overflow = false;

    /*
     * Per RFC 7693 sections 2.5 and 3.3: a keyed BLAKE2b hash has key length
     * greater than 0. The key length is 0 iff the hash is unkeyed (that is,
     * there is no keyed BLAKE2b operation that uses the empty key).
     */
    if (key_len > 0) {
        memcpy(ctx->input_buf, key, key_len);
        memset(ctx->input_buf + key_len, 0, BLAKE2B_BLOCK_BYTES - key_len);
        ctx->bytes_processed_t_low = BLAKE2B_BLOCK_BYTES;
        ctx->input_buf_len = BLAKE2B_BLOCK_BYTES;
    }
    else {
        ctx->bytes_processed_t_low = 0;
        ctx->input_buf_len = 0;
    }
}

int blake2b_add(struct blake2b_ctx *ctx, const byte *bytes, size_t num_bytes)
{
    size_t to_copy;

    if (ctx->bytes_processed_t_overflow) {
        return -1;
    }

    if (ctx->input_buf_len > 0) {
        to_copy = MIN(num_bytes, BLAKE2B_BLOCK_BYTES - ctx->input_buf_len);
        memcpy(ctx->input_buf + ctx->input_buf_len, bytes, to_copy);
        ctx->input_buf_len += to_copy;
        bytes += to_copy;
        num_bytes -= to_copy;
        if (add_to_bytes_processed(ctx, to_copy)) {
            return -1;
        }
        if (num_bytes > 0) {
            compress_fn_f(ctx, ctx->input_buf, false);
            ctx->input_buf_len = 0;
        }
    }

    while (num_bytes > BLAKE2B_BLOCK_BYTES) {
        if (add_to_bytes_processed(ctx, BLAKE2B_BLOCK_BYTES)) {
            return -1;
        }
        compress_fn_f(ctx, bytes, false);
        bytes += BLAKE2B_BLOCK_BYTES;
        num_bytes -= BLAKE2B_BLOCK_BYTES;
    }

    if (num_bytes > 0) {
        if (add_to_bytes_processed(ctx, num_bytes)) {
            return -1;
        }
        memcpy(ctx->input_buf + ctx->input_buf_len, bytes, num_bytes);
        ctx->input_buf_len += num_bytes;
    }
    return 0;
}

int blake2b_end(struct blake2b_ctx *ctx, byte *digest)
{
    byte full_digest[BLAKE2B_MAX_DIGEST_BYTES];
    int i;

    if (ctx->bytes_processed_t_overflow) {
        return -1;
    }

    memset(ctx->input_buf + ctx->input_buf_len, 0,
           BLAKE2B_BLOCK_BYTES - ctx->input_buf_len);
    compress_fn_f(ctx, ctx->input_buf, true);

    for (i = 0; i < 8; i++) {
        put_little_end_64(full_digest + i * 8, ctx->state_h[i]);
    }
    memcpy(digest, full_digest, ctx->digest_len);

    scrub_memory(full_digest, sizeof(full_digest));
    return 0;
}

int blake2b_single(struct blake2b_ctx *ctx, const byte *msg, size_t msg_len,
                   const byte *key, size_t key_len, byte *digest,
                   size_t digest_len)
{
    blake2b_start(ctx, digest_len, key, key_len);
    blake2b_add(ctx, msg, msg_len);
    return blake2b_end(ctx, digest);
}

void blake2b_copy(struct blake2b_ctx *dst, const struct blake2b_ctx *src)
{
    memcpy(dst, src, sizeof(struct blake2b_ctx));
}

void blake2b_free_scrub(struct blake2b_ctx *ctx)
{
    if (ctx != NULL) {
        scrub_memory(ctx, sizeof(struct blake2b_ctx));
        free(ctx);
    }
}

/*
 * Sets the overflow flag, but the calling function is responsible for first
 * checking if it has already been set.
 */
static inline int add_to_bytes_processed(struct blake2b_ctx *ctx, size_t amnt)
{
#if SIZE_MAX > UINT64_MAX
    while (amnt > (size_t)UINT64_MAX) {
        amnt -= (size_t)UINT64_MAX;
        ctx->bytes_processed_t_high++;
        if (ctx->bytes_processed_t_high == 0) {
            ctx->bytes_processed_t_overflow = true;
            return -1;
        }
    }
#endif
    ctx->bytes_processed_t_low += (uint64_t)amnt;
    if (ctx->bytes_processed_t_low < (uint64_t)amnt) {
        ctx->bytes_processed_t_high++;
        if (ctx->bytes_processed_t_high == 0) {
            ctx->bytes_processed_t_overflow = true;
            return -1;
        }
    }
    return 0;
}

